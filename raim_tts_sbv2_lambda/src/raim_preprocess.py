# 辞書では直せない「記号・数字の書き方」を、SBV2 の前処理（normalize_text）に渡す前に言葉へ直す。
#
# 例：w / www（笑い）を「ダブリュー」と読む、25℃ を「ニジュウゴシー」と読む、90% の % が消える、
# 1/3 を「ジュウサン」と読む、など。2026-11-23 にライムが言いそうな203文で確かめて作った。
import re

_SPEAKABLE = re.compile(r"[^\W_]", re.UNICODE)


def raim_preprocess(text: str) -> str:
    t = str(text)
    # ネットの笑い（文末や読点の前の w / ｗ の連続）→ 読まない。前の空白ごと消す。
    # 英単語（web、Wi-Fi など）は前後が英字なので消えない。
    t = re.sub(r"(?:^|(?<=[^\sA-Za-zＡ-Ｚａ-ｚ]))\s*[wWｗＷ]+(?=$|[\s。、！？!?…）)」』])", "", t)
    # 日付 2024/11/23 → 2024年11月23日、11/23 → 11月23日（月・日として正しい数字のときだけ）
    t = re.sub(r"(\d{4})/(\d{1,2})/(\d{1,2})", r"\1年\2月\3日", t)
    t = re.sub(
        r"(?<![\d/])(1[0-2]|0?[1-9])/(3[01]|[12]\d|0?[1-9])(?![\d/])(?=日|に|の|は|まで|から|$|[、。！？\s])",
        r"\1月\2日",
        t,
    )
    # 分数 1/3 → 3ぶんの1（「分の」だと時間の「サンプン」と読まれる）
    t = re.sub(r"(?<![\d/])(\d+)/(\d+)(?![\d/])", r"\2ぶんの\1", t)
    # 時刻 15:30 → 15時30分、9:05 → 9時5分、10:00 → 10時
    t = re.sub(r"(?<!\d)([01]?\d|2[0-3]):00(?!\d)", r"\1時", t)
    t = re.sub(r"(?<!\d)([01]?\d|2[0-3]):0?([1-5]?\d)(?!\d)", r"\1時\2分", t)
    # 範囲 3〜4 → 3から4
    t = re.sub(r"(\d)\s*[〜~～]\s*(\d)", r"\1から\2", t)
    # マイナス -2度 → マイナス2度（数字の前の - で、前が数字・英字でないとき）
    t = re.sub(r"(?<![\dA-Za-z])[-−－](?=\d)", "マイナス", t)
    # 単位
    t = t.replace("℃", "度").replace("°C", "度")
    t = re.sub(r"(\d)\s*[%％]", r"\1パーセント", t)
    # 誘いのくり返し 飲も飲も → 飲も！飲も！（続けて書くとひと続きの「ノモノモ」になるため）。
    # 漢字で始まり、オ段のかなで終わる短い言葉（行こ・遊ぼ・食べよ・帰ろ など）が2回続くときだけ。
    # 「そろそろ」「まあまあ」「ねえねえ」のようなかなだけの言葉は変えない。
    t = _REPEATED_INVITE.sub(lambda m: f"{m.group(1)}！{m.group(1)}{m.group(2) or '！'}", t)
    return t


_REPEATED_INVITE = re.compile(r"([\u4e00-\u9fff][ぁ-ん]{0,2}[おこごそぞとどのほぼぽもよろ])\1(?:[。！!、]|([？?]))?")


def has_speakable_text(text: str) -> bool:
    """読み上げる文字（文字・数字）があるか。"""
    return bool(_SPEAKABLE.search(str(text or "")))
