// downer では「冷たくはない」「からかわない」を明示して区別している。

const DEFAULT_PERSONA = 'bright';

function resolvePersonaName(name) {
  const key = String(name || '').trim().toLowerCase();
  return key === 'downer' || key === 'bright' ? key : DEFAULT_PERSONA;
}

const RAIM_PERSONA = resolvePersonaName(process.env.RAIM_PERSONA);

